import { cloudflare } from '@cloudflare/vite-plugin'
import tailwindcss from '@tailwindcss/vite'
import { tanstackStart } from '@tanstack/react-start/plugin/vite'
import viteReact from '@vitejs/plugin-react'
import { cn } from 'cn/vite'
import compileMessage from 'icu-minify/compile'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { defineConfig, type Plugin } from 'vite'

/**
 * Precompiles `messages/*.json` to icu-minify's compact format, as next-intl's
 * `precompile` option did, so the client ships `use-intl`'s format-only
 * formatter instead of the ICU parser. Also writes `messages/en.d.json.ts`,
 * which types each message's ICU arguments, as `createMessagesDeclaration` did.
 */
function precompileMessages(): Plugin {
  const messagesDir = path.resolve('messages')

  function compile(node: unknown): unknown {
    if (typeof node === 'string') return compileMessage(node)
    if (node && typeof node === 'object') {
      return Object.fromEntries(Object.entries(node).map(([key, value]) => [key, compile(value)]))
    }
    return node
  }

  return {
    name: 'precompile-messages',
    enforce: 'pre',
    async buildStart() {
      const source = JSON.parse(await readFile(path.join(messagesDir, 'en.json'), 'utf8'))
      const declaration = [
        '// This file is auto-generated by vite.config.ts, do not edit directly.',
        '// See: https://next-intl.dev/docs/workflows/typescript#messages-arguments',
        '',
        `declare const messages: ${JSON.stringify(source, null, 2)};`,
        'export default messages;'
      ].join('\n')
      const file = path.join(messagesDir, 'en.d.json.ts')
      if ((await readFile(file, 'utf8').catch(() => '')) !== declaration) {
        await writeFile(file, declaration)
      }
    },
    async load(id) {
      const file = id.split('?')[0]
      if (path.dirname(file) !== messagesDir || path.extname(file) !== '.json') return

      const messages: unknown = JSON.parse(await readFile(file, 'utf8'))
      return {
        code: `export default JSON.parse(${JSON.stringify(JSON.stringify(compile(messages)))})`,
        moduleType: 'js'
      }
    }
  }
}

export default defineConfig(() => {
  return {
    server: { port: 3000 },
    // Keep the existing variable names, so `.env` files and CI secrets need no changes.
    envPrefix: ['VITE_', 'NEXT_PUBLIC_'],
    define: {
      // Only for the Playwright suite, which mocks outbound Resend calls through
      // `lib/test-proxy.server.ts`; a production build compiles it away.
      __E2E_TEST_PROXY__: JSON.stringify(process.env.E2E_TEST_PROXY === '1')
    },
    resolve: {
      tsconfigPaths: true,
      alias: [
        { find: /^use-intl\/format-message$/, replacement: 'use-intl/format-message/format-only' }
      ]
    },
    plugins: [
      // Builds and runs the server in workerd, configured by wrangler.jsonc.
      cloudflare({ viteEnvironment: { name: 'ssr' } }),
      precompileMessages(),
      tailwindcss(),
      cn({ content: ['{app,components,lib}/**/*.{ts,tsx}'], out: 'generated/cn-tables.ts' }),
      tanstackStart({ srcDirectory: 'app' }),
      // React's plugin must come after Start's.
      viteReact({ compiler: true })
    ]
  }
})
