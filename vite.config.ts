const deployEnvs = ['development', 'preview', 'production'] as const
type DeployEnv = (typeof deployEnvs)[number]

/**
 * Which deployment this build is, from the shell (see the `deploy` scripts);
 * unset is `development`. Void deploys a single Cloudflare config, without
 * Wrangler's named environments, so the build carries it: as `__DEPLOY_ENV__`,
 * and as the Sanity dataset, `production` only for production builds. Set in
 * `process.env` before Vite loads `.env`, where a `VITE_*` there would lose.
 */
function readDeployEnv(): DeployEnv {
  const value = process.env.DEPLOY_ENV || 'development'
  const deployEnv = deployEnvs.find((name) => name === value)
  if (!deployEnv) {
    throw new Error(`DEPLOY_ENV must be one of ${deployEnvs.join(', ')}, got "${value}"`)
  }
  process.env.VITE_SANITY_DATASET = deployEnv === 'production' ? 'production' : 'development'
  return deployEnv
}

/**
 * The environment the build was started with, kept from this config's first
 * evaluation: TanStack Start copies every `.env` value into `process.env` while
 * building, and Vite evaluates this config again afterwards.
 */
declare global {
  var __buildShellEnv: NodeJS.ProcessEnv | undefined
}
const shellEnv = (globalThis.__buildShellEnv ??= { ...process.env })

/**
 * Fails a production build that takes a public setting from `.env` rather than
 * the build's environment (Workers Builds' build variables): a laptop's local
 * keys, like Turnstile's test sitekey, would break the live contact form.
 */
function rejectLocalPublicEnv(deployEnv: DeployEnv): Plugin {
  return {
    name: 'reject-local-public-env',
    configResolved() {
      if (deployEnv !== 'production' || !existsSync('.env')) return
      const fromDotenv = Object.keys(parseEnv(readFileSync('.env', 'utf8'))).filter(
        (key) => key.startsWith('VITE_') && shellEnv[key] === undefined
      )
      if (fromDotenv.length > 0) {
        throw new Error(
          `A production build took ${fromDotenv.join(', ')} from .env. Set the production values in the shell.`
        )
      }
    }
  }
}

/**
 * Precompiles `messages/*.json` to icu-minify's compact format, as next-intl's
 * `precompile` option did, so the client ships `use-intl`'s format-only
 * formatter instead of the ICU parser. Also writes `messages/en.d.json.ts`,
 * which types each message's ICU arguments, as `createMessagesDeclaration` did.
 */
function precompileMessages(): Plugin {
  const messagesDir = path.resolve('messages')

  function compile(node: unknown): unknown {
    if (typeof node === 'string') return compileMessage(node)
    if (node && typeof node === 'object') {
      return Object.fromEntries(Object.entries(node).map(([key, value]) => [key, compile(value)]))
    }
    return node
  }

  return {
    name: 'precompile-messages',
    enforce: 'pre',
    async buildStart() {
      const source = JSON.parse(await readFile(path.join(messagesDir, 'en.json'), 'utf8'))
      const declaration = [
        '// This file is auto-generated by vite.config.ts, do not edit directly.',
        '// See: https://next-intl.dev/docs/workflows/typescript#messages-arguments',
        '',
        `declare const messages: ${JSON.stringify(source, null, 2)};`,
        'export default messages;'
      ].join('\n')
      const file = path.join(messagesDir, 'en.d.json.ts')
      if ((await readFile(file, 'utf8').catch(() => '')) !== declaration) {
        await writeFile(file, declaration)
      }
    },
    async load(id) {
      const file = id.split('?')[0]
      if (path.dirname(file) !== messagesDir || path.extname(file) !== '.json') return

      const messages: unknown = JSON.parse(await readFile(file, 'utf8'))
      return {
        code: `export default JSON.parse(${JSON.stringify(JSON.stringify(compile(messages)))})`,
        moduleType: 'js'
      }
    }
  }
}

type ModuleGraphNode = {
  isEntry: boolean
  importers: readonly string[]
  dynamicImporters: readonly string[]
  importedIds: readonly string[]
  dynamicallyImportedIds: readonly string[]
}

/** The lazily loaded modules only draft mode renders. */
const draftModeEntries = new Set(
  ['components/draft-mode.tsx', 'components/optimistic-array.live.tsx'].map((file) =>
    path.resolve(file)
  )
)

/**
 * Tells whether a module of the client graph is loaded only behind a draft
 * mode entry, so chunk groups can leave it out: merged with code visitors
 * load, it pulls Visual Editing into their pages. Walks up to the graph's
 * entries on the first call, then forward from them without entering draft
 * mode entries.
 */
function createDraftModeOnlyCheck() {
  let visitorModules: Set<string> | undefined

  return (id: string, graph: { getModuleInfo(id: string): ModuleGraphNode | null }) => {
    if (!visitorModules) {
      const entries = new Set<string>()
      const seen = new Set([id])
      for (const current of seen) {
        const info = graph.getModuleInfo(current)
        if (!info) continue
        if (info.isEntry) entries.add(current)
        for (const importer of [...info.importers, ...info.dynamicImporters]) seen.add(importer)
      }

      visitorModules = new Set(entries)
      for (const current of visitorModules) {
        const info = graph.getModuleInfo(current)
        if (!info) continue
        for (const imported of [...info.importedIds, ...info.dynamicallyImportedIds]) {
          if (!draftModeEntries.has(imported.split('?')[0])) visitorModules.add(imported)
        }
      }
    }
    return !visitorModules.has(id)
  }
}

export default defineConfig(() => {
  const deployEnv = readDeployEnv()
  const isDraftModeOnly = createDraftModeOnlyCheck()

  return {
    server: { port: 3000 },
    environments: {
      client: {
        build: {
          // The one chunk past Vite's 500 kB default is Visual Editing's, which
          // only draft mode loads; visitors' chunks stay well under this.
          chunkSizeWarningLimit: 650,
          rolldownOptions: {
            output: {
              // Route-level splitting left ~55 files per page, most under 2 KB,
              // which cost a round trip each before hydration. One group
              // merges modules shared by several chunks; `entriesAware` keeps
              // a module with the routes that load it. Merging leftovers up to
              // 50 KB cut pages to ~20 files, but can merge visitors' code with
              // draft-mode-only code, so that code stays out of the group.
              codeSplitting: {
                groups: [
                  {
                    name: (id, context) => (isDraftModeOnly(id, context) ? null : 'shared'),
                    minShareCount: 2,
                    entriesAware: true,
                    entriesAwareMergeThreshold: 50_000
                  }
                ]
              },
              // Merged chunks can import each other, and then one may call
              // into the other before it has run: any import change can move
              // modules into such a cycle and stop every page hydrating. This
              // runs each module's body in source order whatever its chunk,
              // for ~5% more JS.
              strictExecutionOrder: true
            }
          }
        }
      }
    },
    define: {
      // Only production emails the houses (see `app/actions/contact.server.ts`).
      __DEPLOY_ENV__: JSON.stringify(deployEnv),
      // Only for the Playwright suite, which mocks outbound Resend calls through
      // `lib/test-proxy.server.ts`; a production build compiles it away.
      __E2E_TEST_PROXY__: JSON.stringify(process.env.E2E_TEST_PROXY === '1'),
      // The Playwright suite's unresolvable Resend host (see playwright.config.ts),
      // built in: the Worker only gets the secrets env.ts requires.
      ...(process.env.RESEND_BASE_URL && {
        'process.env.RESEND_BASE_URL': JSON.stringify(process.env.RESEND_BASE_URL)
      })
    },
    resolve: {
      tsconfigPaths: true,
      alias: [
        { find: /^use-intl\/format-message$/, replacement: 'use-intl/format-message/format-only' }
      ]
    },
    ssr: { noExternal: true },
    plugins: [
      // Builds and runs the server in workerd, configured by void.config.ts; it
      // must come before Start's.
      rejectLocalPublicEnv(deployEnv),
      voidPlugin(),
      precompileMessages(),
      tailwindcss(),
      cn({ content: ['{app,components,lib}/**/*.{ts,tsx}'], out: 'generated/cn-tables.ts' }),
      tanstackStart({ srcDirectory: 'app' }),
      // React's plugin must come after Start's.
      viteReact({ compiler: true }),
      redact()
    ]
  }
})
